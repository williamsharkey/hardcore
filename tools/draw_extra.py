def triangle(right, solid):
    rows = []
    for y in range(16):
        d = y if y < 8 else 15 - y           # 0..7..0
        if solid:
            bits = (0xFF << (7 - d)) & 0xFF if right else (0xFF >> (7 - d))
        else:
            bits = (0x80 >> d) if right else (0x01 << d)
        rows.append(bits)
    return rows

def to_hex(cp, pic):
    if isinstance(pic, list):
        return "%04X:%s" % (cp, "".join("%02X" % b for b in pic))
    rows = pic.split()
    width = len(rows[0])
    assert len(rows) == 16 and all(len(r) == width for r in rows), hex(cp)
    fmt = "%02X" if width == 8 else "%04X"
    return "%04X:%s" % (cp, "".join(fmt % int(r.replace(".", "0").replace("#", "1"), 2) for r in rows))

GLYPHS[0xE0B0] = triangle(True, True)    # 
