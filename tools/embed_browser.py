#!/usr/bin/env python3
"""Compile browser helpers into native byte arrays; no runtime resource files."""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
assets = {
    'browser_script': b'globalThis.hardcoreSiteAdapters = [];\n' + b'\n'.join(p.read_bytes() for p in sorted((root/'browser/adapters').glob('*.js'))) + b'\n' + (root/'browser/project.js').read_bytes(),
    'browser_welcome': (root/'browser/welcome.html').read_bytes(),
}
target = root/'build/browser.inc'
target.parent.mkdir(exist_ok=True)
with target.open('w') as out:
    out.write('/* Generated by tools/embed_browser.py. */\n')
    out.write('#ifndef HARDCORE_BROWSER_ASSETS_H\n#define HARDCORE_BROWSER_ASSETS_H\n')
    for name, data in assets.items():
        out.write(f'static const unsigned char {name}[] = {{\n')
        for start in range(0,len(data),24):
            out.write(','.join(str(b) for b in data[start:start+24])+',\n')
        out.write('0};\n')
    out.write('#endif\n')
